"""Validate offline PGS language catalogs and generate their resource-independent DEX tables."""
from pathlib import Path
from collections import Counter
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'pgs/i18n'
JAVA = ROOT / 'pgs/src/dev/pgs'
LANGUAGES = ('en', 'de', 'es', 'fr', 'pt-BR', 'ru', 'it', 'zh-Hant', 'nl', 'th', 'ko')
PLACEHOLDER = re.compile(r'(?<![0-9])%(?:(\d+)\$)?[-#+ 0,(<]*\d*(?:\.\d+)?(?:[tT][a-zA-Z]|[bBhHsScCdoxXeEfgGaAn%])')
TEMPLATE_TOKEN = re.compile(PLACEHOLDER.pattern.removeprefix('(?<![0-9])'))


def read(path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError('Duplicate message key in ' + path.name + ': ' + key)
            result[key] = value
        return result
    return json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique)


def placeholders(value):
    # Preserve conversion, explicit argument indexes and numeric formatting, including %%.
    return [m.group() for m in PLACEHOLDER.finditer(value)]


def template_placeholders(value):
    """Parse every percent in a known Formatter template; unescaped/unknown formats are invalid."""
    tokens = []
    offset = value.find('%')
    while offset >= 0:
        token = TEMPLATE_TOKEN.match(value, offset)
        if token is None:
            return None
        tokens.append(token.group())
        offset = value.find('%', token.end())
    return tokens


def compatible_placeholders(source, translated):
    """Allow reordering only when every consuming argument has an explicit stable index.

    Implicit and relative arguments keep their order. The exact token multiset also preserves
    argument types, repeat counts, precision/flags, percent escapes and explicit newlines.
    """
    original, replacement = placeholders(source), placeholders(translated)
    if original:
        # Once a source is a format template, a new stray %q or literal percentage must not
        # bypass validation simply because the recognition regex did not count it as a token.
        original, replacement = template_placeholders(source), template_placeholders(translated)
        if original is None or replacement is None:
            return False
    if original == replacement:
        return True
    consuming = [token for token in original if not token.endswith('%') and token != '%n']
    if any(not re.match(r'%[1-9][0-9]*\$', token) or '<' in token for token in consuming):
        return False
    return Counter(original) == Counter(replacement)


def catalogs():
    source = read(CATALOG / 'en.json')
    if not source or not isinstance(source, dict):
        raise ValueError('English catalog must be a nonempty object')
    for key, value in source.items():
        if not isinstance(key, str) or not key or value != key:
            raise ValueError('English catalog keys must equal their canonical display text')
    result = {'en': source}
    for language in LANGUAGES[1:]:
        messages = read(CATALOG / (language + '.json'))
        if not isinstance(messages, dict):
            raise ValueError(language + ': catalog must be an object')
        if set(messages) != set(source):
            missing, extra = set(source) - set(messages), set(messages) - set(source)
            raise ValueError(f'{language}: {len(missing)} missing, {len(extra)} extra keys; '
                             f'missing sample: {sorted(missing)[:5]}')
        for key, value in messages.items():
            if not isinstance(value, str) or not value.strip() or '\x00' in value:
                raise ValueError(language + ': empty or invalid translation for ' + key)
            if not compatible_placeholders(key, value):
                raise ValueError(language + ': changed formatting placeholders for ' + key)
        result[language] = messages
    return result


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def generated(data):
    notice = '// Generated by tools/i18n_catalog.py. Edit pgs/i18n/*.json instead.\n'
    head = notice + 'package dev.pgs;\n\nimport java.util.Map;\nimport java.util.HashMap;\n\n'
    dispatch = [head, 'final class I18nCatalog {\n    private I18nCatalog() {}\n',
                '    static Map<String, String> load(String language) {\n',
                '        switch (language) {\n']
    output = {}
    for language in LANGUAGES[1:]:
        name = 'I18nCatalog_' + language.replace('-', '_')
        dispatch.append('            case ' + literal(language) + ': return ' + name + '.load();\n')
        messages = sorted(data[language].items())
        chunks = [messages[i:i + 128] for i in range(0, len(messages), 128)]
        lines = [head, 'final class ' + name + ' {\n', '    private ' + name + '() {}\n',
                 '    static Map<String, String> load() {\n',
                 '        Map<String, String> values = new HashMap<>(' + str(len(messages) * 2) + ');\n']
        for i in range(len(chunks)):
            lines.append('        fill' + str(i) + '(values);\n')
        lines.append('        return values;\n    }\n')
        for i, chunk in enumerate(chunks):
            lines.append('    private static void fill' + str(i) + '(Map<String, String> values) {\n')
            for key, value in chunk:
                lines.append('        values.put(' + literal(key) + ', ' + literal(value) + ');\n')
            lines.append('    }\n')
        lines.append('}\n')
        output[JAVA / (name + '.java')] = ''.join(lines)
    dispatch.extend(['            default: return java.util.Collections.emptyMap();\n',
                     '        }\n    }\n}\n'])
    output[JAVA / 'I18nCatalog.java'] = ''.join(dispatch)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = catalogs()
    for path, content in generated(data).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise ValueError('Stale generated language catalog: ' + str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding='utf-8')
    print(f'PGS languages: {len(LANGUAGES)} catalogs, {len(data["en"])} messages each; '
          + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError) as error:
        sys.exit(str(error))
